# ---------------------------------------------------------------- bars


def _bar(h, m, o, hi, lo, c, v="1"):
    return Bar(utc(2024, 1, 16, h, m), D(o), D(hi), D(lo), D(c), D(v))


def test_aggregate_5m_buckets():
    minutes = [_bar(10, m, "1", str(1 + m), "0.5", str(1 + m / 10)) for m in range(0, 7)]
    five = bx.aggregate(minutes, "5m")
    assert [b.ts.minute for b in five] == [0, 5]
    assert five[0].high == D(5) and five[0].close == D("1.4") and five[0].volume == D(5)
    assert five[1].open == D(1) and five[1].volume == D(2)


def test_forex_hours_and_gaps():
    assert not bx.forex_open(utc(2024, 1, 13, 12))  # Saturday
    assert bx.forex_open(utc(2024, 1, 14, 22, 30))  # Sunday 17:30 New York
    assert not bx.forex_open(utc(2024, 1, 19, 22, 30))  # Friday 17:30 New York
    bars = [_bar(10, m, "1", "1", "1", "1") for m in (0, 1, 2, 9, 10)]
    gaps = bx.find_gaps(bars, utc(2024, 1, 16, 10), utc(2024, 1, 16, 10, 11))
    assert [(g.start.minute, g.minutes) for g in gaps] == [(3, 6)]


# ---------------------------------------------------------------- cache


class CountingProvider(DukascopyProvider):
    def __init__(self, base):
        super().__init__(base)
        self.calls = 0

    def fetch_day(self, symbol, day, side):
        self.calls += 1
        return super().fetch_day(symbol, day, side)


def test_cache_fetches_each_day_once(db, mirror):
    p = CountingProvider(f"file://{mirror}")
    start, end = utc(2024, 1, 16, 9), utc(2024, 1, 16, 11)
    cov = md.ensure_range(db, p, "EURUSD", start, end)
    assert cov.status == "ready" and p.calls == 2  # bid + ask
    assert md.ensure_range(db, p, "EURUSD", start, end).status == "ready" and p.calls == 2
    c = db.get(CandleCoverage, ("dukascopy", "EURUSD", DAY))
    assert c.status == "complete" and c.bar_count == len(BID)
    bars = md.load_bars(db, "dukascopy", "EURUSD", "bid", start, end, "1m")
    assert len(bars) == len(BID) and bars[0].ts == utc(2024, 1, 16, 9, 58)


def test_failed_day_is_recorded_and_retried_later(db, mirror):
    class Failing(DukascopyProvider):
        def fetch_day(self, *a):
            raise ProviderUnavailable("network down")

    p = Failing(f"file://{mirror}")
    cov = md.ensure_range(db, p, "EURUSD", utc(2024, 1, 16, 9), utc(2024, 1, 16, 11))
    assert cov.status == "unavailable" and "network down" in cov.failed[DAY]
    good = CountingProvider(f"file://{mirror}")
    assert md.ensure_range(db, good, "EURUSD", utc(2024, 1, 16, 9), utc(2024, 1, 16, 11)).status == "unavailable"
    assert good.calls == 0  # inside the retry window
    c = db.get(CandleCoverage, ("dukascopy", "EURUSD", DAY))
    c.updated_at -= timedelta(hours=1)
    db.commit()
    assert md.ensure_range(db, good, "EURUSD", utc(2024, 1, 16, 9), utc(2024, 1, 16, 11)).status == "ready"


def test_today_is_not_published_yet(db, mirror):
    now = datetime.now(UTC)
    cov = md.ensure_range(db, CountingProvider(f"file://{mirror}"), "EURUSD", now - timedelta(hours=1), now)
    assert cov.unpublished_days == [now.date()] or cov.status in ("partial", "unavailable")


