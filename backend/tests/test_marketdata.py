def test_excursions_survive_policy_change_but_clear_when_fills_change(auth_client, mirror):
    acct, t = _fx_trade(auth_client)
    auth_client.get(f"/api/v1/trades/{t['id']}/chart")
    assert auth_client.patch(f"/api/v1/accounts/{acct['id']}", json={"accounting_policy": "fifo"}).status_code == 200
    assert auth_client.get(f"/api/v1/trades/{t['id']}").json()["mae"] is not None  # same fills, same excursions
    extra = b"Date/Time,Symbol,Side,Quantity,Price,Commission,Fees,Exec ID\n2024-01-16 10:02:10,EURUSD,BUY,5000,1.08990,0.25,0,FX3\n"
    res = import_file(auth_client, acct["id"], "extra.csv", options={"timezone": "UTC"}, data=extra)
    assert res["commit"].status_code == 200
    (after,) = all_trades(auth_client)
    assert after["id"] == t["id"] and after["mae"] is None  # scale-in changed the trade: recompute on next view
