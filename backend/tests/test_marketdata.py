def test_candles_endpoint_and_validation(auth_client, mirror):
    q = {"symbol": "EURUSD", "start": "2024-01-16T09:00:00Z", "end": "2024-01-16T11:00:00Z", "side": "mid"}
    r = auth_client.get("/api/v1/marketdata/candles", params=q)
    assert r.status_code == 200 and len(r.json()["bars"]) == len(BID)
    assert D(r.json()["bars"][0]["o"]) == D("1.08995")  # mid of bid 1.08990 / ask 1.09000
    bad = auth_client.get("/api/v1/marketdata/candles", params=q | {"symbol": "AAPL"})
    assert bad.status_code == 422 and bad.json()["error"]["code"] == "symbol_not_supported"
    too_long = auth_client.get("/api/v1/marketdata/candles", params=q | {"end": "2024-03-30T00:00:00Z"})
    assert too_long.status_code == 422


