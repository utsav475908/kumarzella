def test_excursions_long_ignore_extremes_in_fill_minutes():
    bid = [_bar(10, m, *BID[f"10:{m:02d}"]) for m in range(0, 7)]
    fills = [FillPoint(utc(2024, 1, 16, 10, 0, 30), D(10000), D("1.09000")),
             FillPoint(utc(2024, 1, 16, 10, 5, 20), D(-10000), D("1.09050"))]  # fmt: skip
    r = compute(fills, D(1), bid, [])
    # Worst interior bid low 1.08950 at 10:02, best interior high 1.09080 at 10:03. The 10:00 low (1.08800) and
    # 10:05 high (1.09200) are in fill minutes and must not count.
    assert r.mae == D("-5.00000000") and r.mfe == D("8.00000000")
    assert r.mae_at == utc(2024, 1, 16, 10, 2) and r.mfe_at == utc(2024, 1, 16, 10, 3)
    assert r.minutes_evaluated == 4 and r.minutes_missing == 0


def test_excursions_short_uses_ask():
    ask = [_bar(10, 1, "1.1", "1.1030", "1.0990", "1.1"), _bar(10, 2, "1.1", "1.1010", "1.0950", "1.1")]
    fills = [FillPoint(utc(2024, 1, 16, 10, 0, 10), D(-1000), D("1.1000")),
             FillPoint(utc(2024, 1, 16, 10, 3, 0), D(1000), D("1.0980"))]  # fmt: skip
    r = compute(fills, D(1), [], ask)
    assert r.mae == D("-3") and r.mfe == D("5")


def test_excursions_scale_in_is_policy_independent():
    bars = [_bar(10, 1, "100", "101", "99", "100"), _bar(10, 3, "102", "103", "100", "101"),
            _bar(10, 4, "101", "102", "100.5", "101")]  # fmt: skip
    fills = [FillPoint(utc(2024, 1, 16, 10, 0), D(1), D(100)), FillPoint(utc(2024, 1, 16, 10, 2), D(1), D(102)),
             FillPoint(utc(2024, 1, 16, 10, 5), D(-2), D(101))]  # fmt: skip
    r = compute(fills, D(50), bars, [])
    assert r.mae == D(-100) and r.mfe == D(200)  # (2x100 - 202) x 50 and (2x103 - 202) x 50


def test_excursions_open_trade_is_none():
    assert compute([FillPoint(utc(2024, 1, 16, 10), D(1), D(1))], D(1), [], []) is None


