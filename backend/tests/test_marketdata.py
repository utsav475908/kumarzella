def _fx_trade(client):
    acct = create_account(client, "FX", currency="USD")
    res = import_file(client, acct["id"], "fixture_fx.csv", options={"timezone": "UTC"})
    assert res["commit"].status_code == 200, res["commit"].text
    (t,) = all_trades(client)
    return acct, t


def test_trade_chart_returns_candles_markers_and_excursions(auth_client, mirror):
    _, t = _fx_trade(auth_client)
    assert D(t["net_pnl"]) == D(4)  # 0.00050 x 10000 - 1.00 commission
    r = auth_client.get(f"/api/v1/trades/{t['id']}/chart")
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["status"] == "ready" and body["provider"]["name"] == "dukascopy"
    assert body["bars"][0]["t"] == int(utc(2024, 1, 16, 9, 58).timestamp())
    assert body["bars"][0]["o"] == "1.0899000000"  # decimal strings, never floats
    assert [m["side"] for m in body["markers"]] == ["buy", "sell"]
    ex = body["excursions"]
    assert D(ex["mae"]) == D(-5) and D(ex["mfe"]) == D(8) and ex["source"] == "dukascopy 1m bid/ask"
    detail = auth_client.get(f"/api/v1/trades/{t['id']}").json()
    assert D(detail["mae"]) == D(-5) and D(detail["mfe"]) == D(8)
    five = auth_client.get(f"/api/v1/trades/{t['id']}/chart", params={"timeframe": "5m"}).json()
    assert {b["t"] % 300 for b in five["bars"]} == {0}


