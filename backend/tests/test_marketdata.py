def test_day_path_uses_zero_based_month():
    assert day_path("EURUSD", date(2024, 1, 16), "bid") == "EURUSD/2024/00/16/BID_candles_min_1.bi5"
    assert day_path("USDJPY", date(2024, 12, 2), "ask") == "USDJPY/2024/11/02/ASK_candles_min_1.bi5"


def test_decode_prices_order_and_filler_minutes():
    raw = encode([(0, "1.10000", "1.10020", "1.09990", "1.10010", 2.5), (60, "1.1001", "1.1001", "1.1001", "1.1001", 0.0),
                  (120, "1.10010", "1.10030", "1.10000", "1.10005", 1.0)], "EURUSD")  # fmt: skip
    bars = decode_candles(raw, DAY, D(100000))
    assert [b.ts for b in bars] == [utc(2024, 1, 16, 0, 0), utc(2024, 1, 16, 0, 2)]  # flat zero-volume minute dropped
    b = bars[0]
    assert (b.open, b.high, b.low, b.close, b.volume) == (D("1.1"), D("1.1002"), D("1.0999"), D("1.1001"), D("2.5"))


def test_decode_jpy_scale():
    raw = encode([(0, "148.123", "148.200", "148.100", "148.150", 1.0)], "USDJPY")
    (b,) = decode_candles(raw, DAY, D(1000))
    assert b.open == D("148.123") and b.high == D("148.2")


def test_decode_empty_and_corrupt():
    assert decode_candles(b"", DAY, D(100000)) == []
    with pytest.raises(ProviderError):
        decode_candles(b"not lzma", DAY, D(100000))


def test_decode_rejects_unexpected_layout():
    import lzma
    import struct

    # high below open: what a reordered record layout would look like
    raw = lzma.compress(struct.pack(">IIIIIf", 0, 110000, 110010, 109990, 109000, 1.0), format=lzma.FORMAT_ALONE)
    with pytest.raises(ProviderError, match="low <= open/close <= high"):
        decode_candles(raw, DAY, D(100000))


def test_http_404_is_no_data_and_5xx_is_retried_then_unavailable(monkeypatch):
    monkeypatch.setattr("app.modules.marketdata.providers.dukascopy.time.sleep", lambda s: None)
